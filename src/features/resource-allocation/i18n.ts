export function resourceAllocationCountPhrase(
  locale: Locale,
  count: number,
  kind: CountKind,
): string {
  const category = new Intl.PluralRules(LOCALE_TAGS[locale]).select(count)
  const forms = countForms[locale][kind]
  return `${count} ${forms[category] ?? forms.other}`
}

export function resourceAllocationInterpolate(
  template: string,
  values: Record<string, string | number>,
) {
  return template.replace(/\{([^}]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key)
      ? String(values[key])
      : match,
  )
}


