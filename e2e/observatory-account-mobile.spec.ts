import { expect, test } from '@playwright/test'
import { oidcTestCookies } from './oidc-test-session'

test.describe('Observatory identity and mobile utilities', () => {
  test('profile reveals signed-in subject and all verified roles', async ({ page }) => {
    await page.context().clearCookies()
    await page.context().addCookies(oidcTestCookies(['studio', 'rr_operator', 'observatory_admin']))
    await page.goto('http://observatory.localhost:3000/uk/admin/plugins')
    const profile = page.getByTestId('observatory-profile')
    const avatar = profile.getByRole('button', { name: /Обліковий запис/ })
    await expect(avatar).toBeVisible()
    await expect(avatar).toHaveAttribute('aria-expanded', 'false')
    await avatar.click()
    await expect(avatar).toHaveAttribute('aria-expanded', 'true')
    const panel = page.getByRole('dialog', { name: 'Обліковий запис' })
    await expect(panel).toBeVisible()
    await expect(panel.getByText('ID користувача: local-e2e-account')).toBeVisible()
    await expect(panel.getByText('Адміністратор Observatory')).toBeVisible()
    await expect(panel.getByText('Studio', { exact: true })).toBeVisible()
    await expect(panel.getByText('Оператор RR')).toBeVisible()
    await expect(panel.getByRole('button', { name: 'Вийти' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(avatar).toHaveAttribute('aria-expanded', 'false')
    await avatar.click()
    await page
      .locator('main')
      .first()
      .click({ position: { x: 4, y: 4 } })
    await expect(avatar).toHaveAttribute('aria-expanded', 'false')
  })

  for (const width of [375, 390]) {
    test(`mobile ${width}px shows a readable language selection and bounded profile`, async ({ page }) => {
      await page.setViewportSize({ width, height: 844 })
      await page.context().clearCookies()
      await page.context().addCookies(oidcTestCookies(['observatory_admin']))
      await page.goto('http://observatory.localhost:3000/en/admin/plugins')
      const language = page.getByRole('group', { name: 'Language' })
      await expect(language).toBeVisible()
      await expect(language.locator('a')).toHaveCount(3)
      await expect(language.locator('a[aria-current="page"]')).toHaveText('EN')
      const profile = page.getByTestId('observatory-profile')
      const avatar = profile.getByRole('button', { name: /Account/ })
      await expect(avatar).toBeVisible()
      const bounds = await avatar.boundingBox()
      expect(bounds?.width).toBe(44)
      expect(bounds?.height).toBe(44)
      const groupBox = await language.boundingBox()
      expect(groupBox?.width).toBeLessThanOrEqual(112)
      await avatar.click()
      const panel = page.getByRole('dialog', { name: 'Account' })
      await expect(panel).toBeVisible()
      const rect = await panel.boundingBox()
      expect(rect).not.toBeNull()
      expect(rect!.x).toBeGreaterThanOrEqual(11)
      expect(rect!.x + rect!.width).toBeLessThanOrEqual(width - 11)
      expect(rect!.y).toBeGreaterThanOrEqual((bounds?.y ?? 0) + (bounds?.height ?? 0))
      // Dark-mode menu background is solid, never the 6%-opacity design-system surface.
      const background = await panel.evaluate((node) => window.getComputedStyle(node).backgroundColor)
      expect(background).toBe('rgb(4, 6, 13)')
      const scrollWidth = await page.evaluate(() => document.documentElement.scrollWidth)
      expect(scrollWidth).toBeLessThanOrEqual(width)
      await language.locator('a[data-mobile-locale="uk"]').click()
      await expect(page).toHaveURL('http://observatory.localhost:3000/uk/admin/plugins')
      await expect(page.getByRole('group', { name: 'Мова' }).locator('a[aria-current="page"]')).toHaveText('UK')
    })
  }
})
